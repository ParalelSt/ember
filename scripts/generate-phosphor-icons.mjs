// Usage: node scripts/generate-phosphor-icons.mjs /path/to/phosphor-core/package/assets
// SVG geometry is copied verbatim from the official Phosphor files.
import { readFileSync, writeFileSync } from 'node:fs';
import { resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = fileURLToPath(new URL('../', import.meta.url));
const assets = process.argv[2];
if (!assets) throw new Error('Provide the official phosphor-core assets directory');
const mapping = JSON.parse(readFileSync(resolve(root, 'scripts/phosphor-icons.json'), 'utf8'));
const header = `// Generated by scripts/generate-phosphor-icons.mjs. Do not edit SVG geometry.
// Official Phosphor icons, MIT licensed: https://github.com/phosphor-icons/core
import type { ComponentType, SVGProps } from 'react';

export type IconProps = SVGProps<SVGSVGElement> & {
  size?: number | string;
  /** Accepted for compatibility with former Lucide callers; ignored. */
  absoluteStrokeWidth?: boolean;
};
export type Icon = ComponentType<IconProps>;
`;
const components = mapping.map(({ app, name, weight }) => {
  const svg = readFileSync(resolve(assets, weight, `${name}-${weight}.svg`), 'utf8').trim();
  if (!svg.includes('viewBox="0 0 256 256"')) throw new Error(`Unexpected viewBox: ${name}`);
  const inner = svg.replace(/^<svg\b[^>]*>/, '').replace(/<\/svg>$/, '');
  // These upstream assets contain only JSX-compatible path elements.
  if (!/^(<path d="[^"]*"\s*\/>)+$/.test(inner)) throw new Error(`Review SVG markup: ${name}`);
  return `
/** Phosphor ${name}, ${weight}. */
export function ${app}({ size = 24, width = size, height = size, strokeWidth: _strokeWidth,
  absoluteStrokeWidth: _absoluteStrokeWidth, className, ...props }: IconProps) {
  return (
    <svg xmlns="http://www.w3.org/2000/svg" width={width} height={height}
      viewBox="0 0 256 256" fill="currentColor" {...props}
      className={['phosphor-${name}', className].filter(Boolean).join(' ')}
      aria-hidden={props['aria-label'] !== undefined ? undefined : (props['aria-hidden'] ?? true)}>
      ${inner}
    </svg>
  );
}
`;
});
writeFileSync(resolve(root, 'apps/web/components/icons/phosphor.tsx'), header + components.join(''));
writeFileSync(resolve(root, 'apps/web/components/icons/index.tsx'), `// Shared icon entry point. Keep app names stable across icon libraries.
export type { Icon, IconProps } from './phosphor';
export {
${mapping.map(({ app }) => `  ${app},`).join('\n')}
} from './phosphor';
`);
writeFileSync(resolve(root, 'apps/web/components/icons/PHOSPHOR-LICENSE'),
  readFileSync(resolve(assets, '../LICENSE'), 'utf8').replace(/\r\n/g, '\n'));
const fire = readFileSync(resolve(assets, 'fill/fire-fill.svg'), 'utf8');
writeFileSync(resolve(root, 'apps/web/app/icon.svg'), fire.replace('fill="currentColor"', 'fill="#ff2d2d"') + '\n');
console.log(`Generated ${mapping.length} icons from official SVGs`);
